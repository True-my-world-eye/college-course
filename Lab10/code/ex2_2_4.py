# 习题2.2(4)：分析findall在有/无分组时输出格式的差异

import re

s = "see 123, 1987-02-09 07:30:00, 1986-02-15 07:25:00"

# 无分组：返回完整匹配的字符串列表
fa1 = re.findall(r"\d+-\d+-\d+", s)
print("fa1 (无分组):", fa1)

# 一个分组：只返回分组中的内容
fa2 = re.findall(r"(\d+)-\d+-\d+", s)
print("fa2 (一个分组):", fa2)

# 三个分组：返回元组列表，每个元组对应各分组内容
fa3 = re.findall(r"(\d+)-(\d+)-(\d+)", s)
print("fa3 (三个分组):", fa3)

