import hashlib

class MD5Tool:
    def __init__(self,bytes_list=None):
        self.hash_list=[]
        bytes_list=bytes_list or []
        for b in bytes_list:
            self.calc_MD5(b)
    def calc_MD5(self,b):
        h = hashlib.md5(b).hexdigest()
        self.hash_list.append(h)
        return h

    def comp_MD5(self, b):
        current = hashlib.md5(b).hexdigest()
        if current in self.hash_list:
            print("已存在此MD5:", current)
        else:
            print("新MD5:", current)

